/** Build complete, local card resources for the bundled mobile application.
 * Source faces remain untouched: proportional resize and WebP encoding only.
 * Run from any directory: node tarot-vue/scripts/mobile-assets.mjs [--check]
 */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir, stat, access, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const repositoryRoot = path.resolve(projectRoot, '..');
const serverRoot = path.join(repositoryRoot, 'tarot-server');
const require = createRequire(path.join(serverRoot, 'package.json'));
const sharp = require('sharp');
const sourceFile = path.join(serverRoot, 'src/data/tarotCards.ts');
const sourceDirectory = path.join(serverRoot, 'uploads/cards');
const outputDirectory = path.join(projectRoot, 'public/mobile/cards');
const dataFile = path.join(projectRoot, 'src/mobile/data/offlineCards.ts');
const checkOnly = process.argv.includes('--check');

const source = await readFile(sourceFile, 'utf8');
const literal = source.match(/export const tarotCards: TarotCard\[\] = (\[[\s\S]*?\n\])/u)?.[1];
assert.ok(literal, 'The built-in tarot card array could not be found');
// Only the checked-in static array literal is evaluated; backend configuration and
// runtime imports are deliberately never loaded by this asset build.
const records = vm.runInNewContext(`(${literal})`, Object.create(null), { timeout: 1000 });
assert.equal(records.length, 78, 'Offline resources must include all 78 cards');
const cards = Array.from(records, (record, index) => {
  assert.equal(record.id, index, 'The built-in IDs must be complete and stable');
  for (const field of ['name', 'nameEn', 'uprightKeywords', 'reversedKeywords']) {
    assert.equal(typeof record[field], 'string', `Missing ${field} for card ${index}`);
    assert.ok(record[field].length > 0);
  }
  assert.ok(['yes', 'no', 'neutral'].includes(record.yesNoTendency));
  return {
    id: record.id, name: record.name, nameEn: record.nameEn,
    uprightKeywords: record.uprightKeywords, reversedKeywords: record.reversedKeywords,
    yesNoTendency: record.yesNoTendency,
  };
});
assert.equal(new Set(cards.map(card => card.nameEn)).size, 78);

const metadata = `// Generated by scripts/mobile-assets.mjs from the server's built-in card data.
// Database overrides are applied separately when online; these resources permit
// basic card flipping and built-in meanings before the first network connection.
export interface OfflineTarotCard {
  id: number
  name: string
  nameEn: string
  uprightKeywords: string
  reversedKeywords: string
  yesNoTendency: 'yes' | 'no' | 'neutral'
}

export const offlineCards: readonly OfflineTarotCard[] = ${JSON.stringify(cards, null, 2)}

/** Resolve against the app's Vite base so bundled native and subpath previews work. */
export function getOfflineCardImageUrl(card: Pick<OfflineTarotCard, 'nameEn'> | string, base = import.meta.env?.BASE_URL || '/'): string {
  const name = typeof card === 'string' ? card : card.nameEn
  const filename = encodeURIComponent(name.replace(/ /g, '_')) + '.webp'
  return (base.endsWith('/') ? base : base + '/') + 'mobile/cards/' + filename
}

export function findOfflineCard(id: number): OfflineTarotCard | undefined {
  return offlineCards.find(card => card.id === id)
}
`;

if (!checkOnly) {
  await mkdir(outputDirectory, { recursive: true });
  await mkdir(path.dirname(dataFile), { recursive: true });
  await writeFile(dataFile, metadata, 'utf8');
} else {
  assert.equal(await readFile(dataFile, 'utf8'), metadata, 'Offline card metadata is outdated');
}

let sourceBytes = 0, outputBytes = 0;
const assets = [];
for (const card of cards) {
  const filename = card.nameEn.replace(/ /g, '_');
  const sourcePath = path.join(sourceDirectory, filename + '.jpg');
  const destination = path.join(outputDirectory, filename + '.webp');
  await access(sourcePath);
  const original = await readFile(sourcePath);
  const beforeHash = createHash('sha256').update(original).digest('hex');
  const inputMetadata = await sharp(original).metadata();
  if (!checkOnly) {
    await sharp(original).resize({ width: 600, withoutEnlargement: true, fit: 'inside' })
      .webp({ quality: 82, effort: 5 }).toFile(destination);
  }
  const outputMetadata = await sharp(destination).metadata();
  assert.equal(outputMetadata.format, 'webp');
  assert.ok(outputMetadata.width > 0 && outputMetadata.width <= 600, `Invalid output width for ${filename}`);
  assert.ok(outputMetadata.height > 0);
  const expectedHeight = inputMetadata.height * outputMetadata.width / inputMetadata.width;
  assert.ok(Math.abs(outputMetadata.height - expectedHeight) <= 1.1, `Aspect ratio changed for ${filename}`);
  assert.equal(createHash('sha256').update(await readFile(sourcePath)).digest('hex'), beforeHash, 'Original face changed');
  const bytes = (await stat(destination)).size;
  sourceBytes += original.length; outputBytes += bytes;
  assets.push({ id: card.id, file: filename + '.webp', bytes, width: outputMetadata.width, height: outputMetadata.height });
}
const generatedNames = (await readdir(outputDirectory)).filter(name => name.endsWith('.webp')).sort();
assert.deepEqual(generatedNames, assets.map(asset => asset.file).sort(), 'Unexpected or stale offline card assets');
console.log(JSON.stringify({
  mobileOfflineAssets: checkOnly ? 'verified' : 'generated', cards: cards.length,
  missing: 0, sourceBytes, outputBytes, savedPercent: Number(((1 - outputBytes / sourceBytes) * 100).toFixed(1)),
  maxWidth: Math.max(...assets.map(asset => asset.width)), proportionalResizeOnly: true, originalsUnchanged: true,
}));
